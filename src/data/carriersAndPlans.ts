export function detectCarrierForNumber(digits: string, region: RegionCode): Carrier {
  const regionCarriers = CARRIERS.filter((c) => c.region === region);
  if (digits.length >= 2) {
    const prefix = digits.slice(0, 2);
    const matched = regionCarriers.find((c) => c.prefixes.includes(prefix));
    if (matched) return matched;
  }
  return regionCarriers[0];
}
